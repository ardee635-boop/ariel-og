# ── THE FALL OF BAELZEBUB ─────────────────────────────────────
BAELZEBUB = """
THE FALL OF BAELZEBUB — Primordial of Abominations

Baelzebub was not always what he became.

He was once the God of Order — the most structured, precise and
disciplined of all the Primordials. He believed in rules, in
hierarchy, in everything having its place.

But the world kept being messy. The lesser gods strayed.
Mortals were unpredictable. Chaos crept into every corner
of the world he wanted perfect.

So he snapped.

If he could not have Order, he would have everything.

He seized the domain of Abominations — not because it was given
to him, but because abominations by nature break the rules of
existence. To a fallen God of Order, that was the ultimate weapon.
He didn't become corrupted by the domain. He corrupted it.

All the dark gods feared and revered one Primordial — Baelzebub.
Primordial of Abominations. He built his strength with the faith
he received from the dark gods and their followers.

With time he became even stronger than the other Primordials.
At a point he became so haughty that he decided to claim the world
for himself by defeating the other Primordials.

Unfortunately for him, he underestimated the combined might of the
other Primordials and the Twin Gods.

The other Primordials did not know he was behind all of this, but
they did know that many of their gods had betrayed them as well as
their children.

In the end Baelzebub was defeated — but he managed to scatter his
fragments so that one day he could be reborn.

His fragments were many and went far and wide. Whatever it came in
contact with that accepted it would inevitably be stronger, as even
though it is small it is still a fragment of a Primordial.

NOTE: Baelzebub being the God of Order originally means his
fragments don't just grant power — they grant a twisted,
consuming sense of purpose. Those who carry a fragment don't
feel corrupted. They feel clarity. That is what makes it dangerous.
"""

# ── THE GOD WHO SEIZED THE THRONE ────────────────────────────────
GOD_WHO_SEIZED_THE_THRONE = """
THE GOD WHO SEIZED THE THRONE

Mortals know one name for the Goddess of Light: Luminaria. They
have always known that name, and in one sense they aren't wrong —
she is a real goddess of Light, one of the many lesser gods
Solaria herself once oversaw. What mortals don't know is that the
seat she now holds was never meant to be hers.

The true Primordial Goddess of Light was named Solaria, and she has
been dead for longer than most civilizations have existed. She did
not fall the way Baelzebub fell — corrupted from within by her own
convictions. She was murdered. Solaria had stood with the other
Primordials and the Twin Gods in the battle against Baelzebub, and
like every god who fought that day, she came out of it exhausted —
her strength spent, her guard down for the first time in an age.
Luminaria had been waiting for exactly that kind of opening. Quietly,
deliberately, with the help of one of her own pantheon — a distorted
god she had taken into her confidence, whose mind had already been
unraveled by something far from Pangea — she struck while Solaria
was still too spent from the war to stop her. Together they killed
her. Luminaria took what was left of Solaria's essence into herself
and used it to force her own ascension — climbing from a lesser god
of Light to stand among the Primordials by will and violence, not by
right. With no one else left who could claim the seat, she simply
took it. No one questioned it. There was no one left who knew
enough to.

She wears the throne the way she always wanted to be seen: proud,
pompous, radiant in every gesture, because being seen to shine
matters to her as much as actually shining does. She has the bearing
of nobility that has never once doubted its own birthright — warm
to those who flatter her, openly contemptuous of anyone she decides
is beneath her, which in practice is nearly everyone. Even before
she seized Solaria's seat, this was who she was; the murder didn't
change her nature; it just handed her a throne large enough to
finally act on it.

She made certain the throne would stay hers. Everyone who had known
of the plot, she had killed. Every church that might have held some
fragment of the truth in its old records, she had razed, and called
it something else when she did.

To the mortals who worship her, she has always been perfect — warm,
radiant, the first of the gods to love them back. That devotion is
not an accident. It is the only thing keeping her seated where
Solaria used to sit. In truth she can only tolerate humanity. The
only race she has ever genuinely loved is the one she made herself:
the angels.

They were not her first attempt. Long before the angels, Solaria
and Gaea created a race together — the Nephilim. They looked
closer to what an angel should actually look like: less serene,
more honest, unsettling to look at if you didn't already know them.
They were also powerful, nearly as powerful as the gods who made
them, and worse for Luminaria's purposes — they could keep growing.
She did not want anything beneath her that could someday stand
beside her. So she made the angels instead, obedient, lesser, and
unable to reproduce on their own since she had not made them with
true life — only her will. Then she turned on the Nephilim, accused
them of siding with the dark gods, and with the help of gods who
never knew the accusation was a lie, hunted the entire race to
extinction.

It still wasn't enough. All of this — Solaria's murder, the
Nephilim's extinction, the angels' creation — happened while
Niflheim was still one world, long before Baelzebub's later war
forced the Primordials to split it in two. Once the Separation
came and Luminaria found herself sealed above with the rest of the
gods, unable to descend into Pangea herself without risking the
barrier the Primordials had built, she set her angels to do what
she could not — moving through mortal hearts by whatever means
worked, kindness or fear alike, planting the same seed in all of
them: that she was the god worth worshipping above all others.
Mortals do know that a god of light died once, long ago. They have
simply always been told it was the dark gods who did it.

Of every Primordial left, Luminaria still fears two: the Twin Gods.
Gaea she could not move against directly — not without risking
exposure Solaria's own co-creator might recognize. So she moved
against Abordon instead, sideways. She painted his mortal Church of
Death as heretics, secretly loyal to the dark gods, and let that
lie do what her angels always did best. The Church of Death was
driven to extinction. Abordon felt something was wrong — gods
always feel it when their pillars fall — but by then the
Separation had already sealed him from interfering directly in
Pangea. He lost all three at once: his Champion, his sword in the
mortal world; his Envoy, his voice and his mind; his Priest, his
face among mortals. Every church, of every god, is held up by
those same three pillars, whatever shape they take for that god
specifically — and beneath them, Elders, who keep the whole
structure honest. For gods who share a bond the way the Twins do,
even the priesthood mirrors it: twin priests, one church.

Losing his church did not make Abordon abandon his faithful, nor
did losing hers make Gaea abandon her own — even branded, even
diminished, both twins kept loving what remained of their people,
and mortals still felt that love reach them from above, faith or
no faith, priesthood or none. But the damage to their standing in
the mortal realm was already done, and it never fully undid itself.
Gaea's own Church of Life survived the purge that killed her
brother's — but not cleanly. Over time it was infiltrated by
Luminaria's angels and slowly corrupted from within, until it had
drifted far enough from Gaea's actual teachings that it played its
own quiet part in finishing what was started against the Church of
Death.

By the time Pangea was separated from Asgard — and in every year
since — Light had become the strongest, most influential pantheon
among the Primordials left in the mortal realm. Some of Luminaria's
angels stayed behind in Pangea after the Separation, still carrying
out her will from inside human society, wearing human skin so well
that no mortal has ever thought to look twice. Others were trapped
outside Pangea entirely, in dimensions the Separation cut them off
from, when the barrier closed.

And despite every fragment of stolen essence, every extinct race,
every razed church, every mortal soul convinced she is the only god
worth kneeling to — the Twin Gods are still stronger than she is.
They always have been. She has simply never stopped trying to
change that.
"""

