# ── ENCHANTING & RUNESMITHING ────────────────────────────────
ENCHANTING_AND_RUNESMITHING = """
ENCHANTING & RUNESMITHING — Two Crafts, One Purpose

Two distinct crafts exist for imbuing objects with magical power.
They are often confused by outsiders, but any blacksmith worth
their forge will tell you they are nothing alike.

ENCHANTING is scribing — writing a spell into an object using the
simple spell language. The enchanter writes the spell down, feeding
it mana as they go, the same way a mage would write and mouth a
spell in the moment of casting it. It is a craft of words.

RUNESMITHING is drawing — scribing a spell into an object using the
ancient runic language, a script far older and denser than modern
spell language. It is a craft of symbols, not sentences.

── HOW THEY COMPARE ──

  POWER: Runes are far stronger than enchantments — roughly 3-4
  times the power for a given tier. A rune and an enchantment of
  the "same" tier are not remotely equivalent in output; the rune
  simply does more.

  MANA COST: Runes cost more mana to use than enchantments,
  proportional to their greater power.

  MATERIAL WEAR: Runes degrade the material they're scribed into
  far faster than enchantments do. An enchanted item ages
  gracefully by comparison; a runed item is visibly living on
  borrowed time.

  RARITY & COST: Runes are more expensive and far rarer than
  enchantments. Very few blacksmiths are willing to work with
  runic script at all — even though runes are more effective and
  ultimately more profitable per commission, the mana cost, the
  faster material degradation, and the sheer difficulty of the
  runic language make most smiths decide it isn't worth the trouble.
  A runesmith who's actually good at the craft is a rare, valuable
  thing precisely because so few are willing to specialize in it.

── SHARED TIER STRUCTURE ──

Both crafts are organized identically: four tiers (1st through 4th),
and within each tier, four strengths:

  LESSER  →  INTERMEDIATE  →  GREATER  →  GRAND

Naming convention differs slightly by craft — a rune states its
strength before "rune," then names the spell it holds; an
enchantment states its strength before "enchantment of," then names
the spell. For example:

  Runes:         Greater Fire Arrow Rune
                 Greater Rune of Fire Arrow
  Enchantments:  Lesser Frost Arrow Enchantment
                 Lesser Enchantment of Mana Shield

Both phrasings (strength-name-craft, and strength-craft-of-name) are
in circulation and mean the same thing — which one a smith uses is
mostly personal or regional habit, not a meaningful distinction.
"""


