# ── TOWNIA & THE CURSED CHILDREN ─────────────────────────────
TOWNIA = """
TOWNIA — The Town of Beginnings

Townia is not part of Pangea. It does not sit on any map of the
mortal realm, on any continent, in any region a traveler could
walk to. It is its own dimension entirely — a pocket outside the
world proper, built for exactly one purpose: to be where the dead
wake up when the Twin Gods decide they are not finished living.

Every soul that wakes in Townia woke there because of the same
war — Baelzebub's uprising, the battle against the dark gods, the
one that eventually forced the Separation itself. Many souls
perished in that war, foreign and local both, and the Twin Gods —
Abordon, who holds Death, and Gaea, who holds Life — were saddened
by the scale of it. Between the two of them lies everything Death
and Life could ever touch, beginning and end both, and so between
them they made something no other god could: a second chance.
Using that shared authority, they gave the fallen a way back into
living, infinitely, for as long as it was needed. Townia is where
that gift takes shape. A soul wakes there with no memory of the
life or death that came before it — only the gift itself, waiting.

They were called the Blessed Ones, at first. That did not last.
To die and come back, and die and come back again, over and over,
stopped looking like a blessing to the people who watched it happen
and started looking like something wrong with the ones it kept
happening to. The name that stuck instead was CURSED CHILDREN — and
it is the name that has stuck ever since, spoken sometimes with
awe, sometimes with real fear, rarely with anything as simple as
the gratitude the Twins originally intended.

TOWNIA'S ONE RULE: leaving is permanent. There are a number of
ways out — the game mechanically represents this as registration,
naming, the moment a cursed child steps into their first real
action in the world — but however it happens, it only happens once.
Once a cursed child leaves Townia, Townia will not open to them
again. Not as a destination. Not as a place to return and rest.
It was never meant to be lived in — only woken up in.

WHAT HAPPENS WHEN A CURSED CHILD DIES AGAIN: the gift the Twins
gave is not a one-time miracle spent on the war's dead. It renews.
A cursed child who dies again in Pangea does not go back to
Townia — that door is closed for good the moment they first
leave it — but the same rebirth the Twins wove into every cursed
child triggers again regardless, and they wake once more, whole,
in the town they most recently called their own. Usually that is
somewhere on the Central Continent, since that is where most
cursed children's stories tend to begin and settle, but it is not
a fixed rule — a cursed child who has rooted themselves elsewhere,
built a life or a guild or a home in another town entirely, will
find themselves waking there instead. The rebirth follows the
child, not the map.

Not everyone is glad the cursed children exist. To some, they are
proof the Twin Gods still love the world enough to fight for it,
soul by soul. To others, a person who cannot seem to permanently
die is not a miracle — it is a curse worn as a person, and Pangea
has never fully agreed on which one it's looking at.
"""

