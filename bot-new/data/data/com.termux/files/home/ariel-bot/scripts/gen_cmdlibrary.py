"""
Phase 1 of the command library: READ-ONLY inventory. Scans the code and writes
cmdlibrary.json at the repo root (one entry per command, with every place that
handles it, which pool set it is in, and duplicates flagged). Nothing in the bot
reads this file yet. Re-run any time:  python3 scripts/gen_cmdlibrary.py
"""
import ast, glob, json, os, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
rd = lambda f: open(f, encoding="utf-8", errors="replace").read()
CMD = r"\.[a-z][a-z0-9_]{1,24}"
entries = collections.defaultdict(lambda: {"handlers": [], "sets": []})

def add(cmd, side, file, line, kind):
    h = {"side": side, "file": file, "line": line, "kind": kind}
    if h not in entries[cmd]["handlers"]:
        entries[cmd]["handlers"].append(h)

# ---------- Python ----------
PY_SET = re.compile(r"^\s*([A-Z_]+_CMDS|ARENA_ALLOWED)\s*=\s*\{")
for f in sorted(glob.glob("engine/router/*.py") + glob.glob("engine/router/*/*.py")):
    src = rd(f); L = src.split("\n")
    # command sets (name -> members)
    for i, l in enumerate(L):
        m = PY_SET.match(l)
        if m:
            j = i
            while j < len(L) and "}" not in L[j]: j += 1
            for c in re.findall(r'"(' + CMD + r')"', "\n".join(L[i:j + 1])):
                entries[c]["sets"].append(f"{m.group(1)} ({os.path.basename(f)})")
    # handler comparisons
    for i, l in enumerate(L, 1):
        for m in re.finditer(r'\bcmd\s*(?:==|in)\s*(\(?[^:\n]*)', l):
            for c in re.findall(r'"(' + CMD + r')"', m.group(1)):
                add(c, "python", f, i, "dispatch")
    # table-style: {".x": handler}
for f in sorted(glob.glob("engine/bridge.py")):
    pass

# ---------- JS ----------
JS_FILES = sorted(glob.glob("bot/**/*.js", recursive=True))
for f in JS_FILES:
    L = rd(f).split("\n")
    for i, l in enumerate(L, 1):
        for m in re.finditer(r"""(?:\b(?:cmd|lower|lowerCmdOnly|command|firstWord)\s*===\s*|startsWith\()\s*['"`](""" + CMD + r""")""", l):
            add(m.group(1), "js", f, i, "dispatch")
    src = "\n".join(L)
    for name in ("NORMAL_FUN_COMMANDS", "ROYALTY_POOL"):
        m = re.search(r"(?:const|let)\s+" + name + r"\s*=\s*new Set\(\[(.*?)\]\)", src, re.S)
        if m:
            for c in re.findall(r"""['"](""" + CMD + r""")['"]""", m.group(1)):
                entries[c]["sets"].append(f"{name} ({os.path.basename(f)})")

# ---------- menu mentions ----------
menu_files = ["engine/pokemon/interfaces.py", "engine/router/handle.py"] + JS_FILES
for c in list(entries):
    pass

# ---------- classify ----------
def infer_pool(c, e):
    sets = " ".join(e["sets"])
    if "ROYALTY_POOL" in sets: return "admin"
    if "POKEMON_CMDS" in sets: return "pokemon"
    if "NORMAL_CMDS" in sets or "NORMAL_FUN_COMMANDS" in sets or "GLOBAL_CMDS" in sets: return "normal"
    files = " ".join(h["file"] for h in e["handlers"])
    for key, pool in (("router/rpg", "rpg"), ("amongus", "amongus"), ("work.js", "silent"), ("router/lord", "admin"),
                      ("commands.js", "admin"), ("router/admin", "admin"), ("router/gamble", "normal")):
        if key in files: return pool
    return "unknown"

out = {}
for c in sorted(entries):
    e = entries[c]
    sides = sorted({h["side"] for h in e["handlers"]})
    out[c] = {
        "pool": infer_pool(c, e),
        "owner": "+".join(sides) if sides else "none",
        "duplicate": len(sides) > 1 or len({(h["file"]) for h in e["handlers"] if h["side"] == "python"}) > 1,
        "sets": sorted(set(e["sets"])),
        "handlers": e["handlers"],
        "min_rank": None,   # phase 2: fill from ROYALTY_POOL / .ascmd overrides
        "help": None,       # phase 3: menu text will be generated from this
    }
doc = {"_note": "Generated by scripts/gen_cmdlibrary.py (phase 1, read-only). Nothing reads this yet.",
       "count": len(out),
       "duplicates": sorted(c for c, v in out.items() if v["duplicate"]),
       "unknown_pool": sorted(c for c, v in out.items() if v["pool"] == "unknown"),
       "commands": out}
json.dump(doc, open("cmdlibrary.json", "w"), indent=1)
print("commands:", len(out))
print("by pool:", dict(collections.Counter(v["pool"] for v in out.values())))
print("by owner:", dict(collections.Counter(v["owner"] for v in out.values())))
print("duplicates:", doc["duplicates"])
